/**
 * Detects the UI locale ('en' | 'es') from the browser's language settings.
 * Checks navigator.languages (in preference order), then navigator.language.
 * Falls back to English when no Spanish preference is found.
 */
export function getLocale() {
  if (typeof navigator === 'undefined') return 'en'
  const candidates = [
    ...(navigator.languages || []),
    navigator.language,
  ].filter(Boolean)
  const prefersSpanish = candidates.some(
    (l) => l.toLowerCase().split('-')[0] === 'es',
  )
  return prefersSpanish ? 'es' : 'en'
}

/**
 * Hook-style helper — returns t() and isSpanish based on the browser locale.
 * t(key) returns the translated string; t(key, ...args) calls it if it's a function.
 */
export function useTranslations() {
  const locale = getLocale()
  const dict = translations[locale]

  const t = (key, ...args) => {
    const val = dict[key] ?? translations.en[key] ?? key
    return typeof val === 'function' ? val(...args) : val
  }

  return { t, isSpanish: locale === 'es', locale }
}
